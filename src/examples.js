/* 워크시트 데이터에 예시와 힌트를 붙인다 */
function attachHelp(src, key) {
  COURSES.campaign.sheets.forEach((sheet) => {
    const ex = src[sheet.id]; if (!ex) return;
    sheet.blocks.forEach((b) => {
      const e = ex[b.id]; if (e === undefined) return;
      if (b.type === 'table') b.rows.forEach((row, r) => { if (e[r]) row[key] = e[r]; });
      else b[key] = e;
    });
  });
}
attachHelp(EXAMPLES, 'ex');
attachHelp(NUDGES, 'nudge');
